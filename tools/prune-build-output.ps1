[CmdletBinding(SupportsShouldProcess)]
param(
    # Build output not written for this long is treated as abandoned.
    [int]$IdleHours = 12,
    # Folders whose child worktrees may carry their own `target` directories.
    [string[]]$WorktreeRoots = @(
        'D:\Projects\wow\worktrees',
        'D:\Projects\wow\worktrees\worktrees',
        'D:\Projects\wow\worktrees-legacy',
        'D:\Projects\wow\client\.claude\worktrees'
    ),
    # The primary checkout's target directory; only stale pieces inside it are removed.
    [string]$PrimaryTarget = (Join-Path (Split-Path -Parent $PSScriptRoot) 'target')
)
# Removes build output nobody is using, so builds stop filling the disk:
# - an agent worktree's whole `target` directory once nothing under it was written for
#   $IdleHours (a running build writes constantly, so it is never touched);
# - inside the primary `target`, incremental-compilation sessions and per-profile build
#   folders not written for $IdleHours, plus the stale `debug` profile when the dx
#   (`desktop-dev`) profile is the one in use.
# Everything removed is regenerated by the next build. Source, notes and git state are never
# touched.
$ErrorActionPreference = 'Stop'
$cutoff = (Get-Date).AddHours(-$IdleHours)
$freed = 0L

function Get-NewestWrite([string]$Path) {
    # A folder's time changes when an entry is created, renamed or removed in it, which every
    # build step does somewhere; the newest folder anywhere below is the last build activity.
    # (Top-level folder times alone miss a build that only wrote deep inside, e.g. dx's bundle.)
    $newest = (Get-Item -LiteralPath $Path).LastWriteTime
    foreach ($dir in Get-ChildItem -LiteralPath $Path -Directory -Recurse -Force -ErrorAction SilentlyContinue) {
        if ($dir.LastWriteTime -gt $newest) { $newest = $dir.LastWriteTime }
    }
    $newest
}

function Remove-BuildDir([string]$Path, [string]$Why) {
    $size = (Get-ChildItem -LiteralPath $Path -Recurse -File -Force -ErrorAction SilentlyContinue |
        Measure-Object -Property Length -Sum).Sum
    if ($PSCmdlet.ShouldProcess($Path, "remove ($Why, $([math]::Round($size / 1GB, 1)) GB)")) {
        Remove-Item -LiteralPath $Path -Recurse -Force -ErrorAction SilentlyContinue
        if (!(Test-Path -LiteralPath $Path)) {
            $script:freed += $size
            Write-Host "pruned $Path ($([math]::Round($size / 1GB, 1)) GB, $Why)"
        } else {
            Write-Warning "could not fully remove $Path (in use?)"
        }
    }
}

foreach ($root in $WorktreeRoots) {
    if (!(Test-Path -LiteralPath $root)) { continue }
    foreach ($tree in Get-ChildItem -LiteralPath $root -Directory -ErrorAction SilentlyContinue) {
        $target = Join-Path $tree.FullName 'target'
        if ((Test-Path -LiteralPath $target) -and (Get-NewestWrite $target) -lt $cutoff) {
            Remove-BuildDir $target "worktree build idle > ${IdleHours}h"
        }
    }
}

$busy = Get-Process dx, cargo, rustc, lld-link, link -ErrorAction SilentlyContinue
$busy += Get-Process -ErrorAction SilentlyContinue | Where-Object { $_.ProcessName -like 'benilla*' }
if ($busy) {
    Write-Host "primary target left alone: $(@($busy.ProcessName | Select-Object -Unique) -join ', ') running"
} elseif (Test-Path -LiteralPath $PrimaryTarget) {
    # Incremental sessions: one folder per crate build; old ones are never read again.
    foreach ($inc in Get-ChildItem -LiteralPath $PrimaryTarget -Directory -Recurse -Filter 'incremental' -Depth 3 -ErrorAction SilentlyContinue) {
        foreach ($session in Get-ChildItem -LiteralPath $inc.FullName -Directory -ErrorAction SilentlyContinue) {
            if ($session.LastWriteTime -lt $cutoff) { Remove-BuildDir $session.FullName 'old incremental session' }
        }
    }
    # Whole profile folders (debug, release, play, ship, x86_64-…\desktop-dev, dx, …) left idle.
    $profiles = @(Get-ChildItem -LiteralPath $PrimaryTarget -Directory -ErrorAction SilentlyContinue)
    $triple = Join-Path $PrimaryTarget 'x86_64-pc-windows-msvc'
    if (Test-Path -LiteralPath $triple) {
        $profiles = @($profiles | Where-Object { $_.FullName -ne $triple }) +
            @(Get-ChildItem -LiteralPath $triple -Directory -ErrorAction SilentlyContinue)
    }
    foreach ($profile in $profiles) {
        if ((Get-NewestWrite $profile.FullName) -lt $cutoff) {
            Remove-BuildDir $profile.FullName "build profile idle > ${IdleHours}h"
        }
    }
}

Write-Host "build output pruned: $([math]::Round($freed / 1GB, 1)) GB freed"
